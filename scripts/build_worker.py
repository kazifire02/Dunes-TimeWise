"""Bundle Jinja templates and publish only the CSS/logo as static assets."""

from pathlib import Path
import shutil

root = Path(__file__).resolve().parents[1]
source = root / "src"
source.mkdir(exist_ok=True)
for name in ("app.py", "database.py", "neon_http.py", "passwords.py", "worker.py"):
    destination = source / name
    if not destination.exists() or destination.read_bytes() != (root / name).read_bytes():
        shutil.copy2(root / name, destination)
templates = {
    str(path.relative_to(root / "templates")): path.read_text(encoding="utf-8")
    for path in sorted((root / "templates").rglob("*.html"))
}
template_module = (
    "# Generated by scripts/build_worker.py; edit templates/ instead.\n"
    + "TEMPLATES = " + repr(templates) + "\n"
)
destination = source / "bundled_templates.py"
if not destination.exists() or destination.read_text(encoding="utf-8") != template_module:
    destination.write_text(template_module, encoding="utf-8")
assets = root / "public" / "static"
assets.mkdir(parents=True, exist_ok=True)
for path in (root / "static").iterdir():
    if path.is_file() and path.suffix.lower() in {".css", ".png", ".svg", ".ico", ".js"}:
        destination = assets / path.name
        if not destination.exists() or destination.read_bytes() != path.read_bytes():
            shutil.copy2(path, destination)
print(f"Bundled {len(templates)} templates and static assets.")
