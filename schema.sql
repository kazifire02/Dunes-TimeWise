-- Run once in the Neon SQL Editor. Safe to rerun; never drops existing data.
-- Arrival timestamps remain Dubai local wall-clock time to match the app.
BEGIN;

CREATE TABLE IF NOT EXISTS staff_users (
    staff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'staff'
);

CREATE TABLE IF NOT EXISTS student_roster (
    student_no TEXT PRIMARY KEY,
    student_name TEXT NOT NULL,
    grade TEXT NOT NULL,
    section TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS staff_users_username_lower_idx ON staff_users (lower(username));

CREATE TABLE IF NOT EXISTS late_arrivals (
    arrival_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name TEXT NOT NULL,
    grade TEXT NOT NULL,
    section TEXT NOT NULL,
    arrival_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    recorded_by TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS late_arrivals_time_idx ON late_arrivals (arrival_time);
CREATE INDEX IF NOT EXISTS late_arrivals_student_idx
    ON late_arrivals (lower(trim(student_name)), grade, section, arrival_time);
CREATE INDEX IF NOT EXISTS student_roster_class_idx ON student_roster (grade, section);

COMMIT;
